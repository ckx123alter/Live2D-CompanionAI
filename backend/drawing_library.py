def choose_drawing(recent):
    """Exclude the last 19 subjects so all 20 can appear before repeating."""
    candidates = [key for key, drawing in PREPARED_DRAWINGS.items() if drawing['name'] not in recent[:19]]
    key = secrets.choice(candidates or list(PREPARED_DRAWINGS))
    drawing = copy.deepcopy(PREPARED_DRAWINGS[key])
    # Uniform sampling preserves the existing slow, smooth stroke animation.
    paths = []
    for path in drawing['strokes']:
        points = [path[0]]
        for a, b in zip(path, path[1:]):
            count = max(1, math.ceil(math.dist(a, b)/5))
            points.extend([round(a[k]+(b[k]-a[k])*i/count, 2) for k in (0, 1)] for i in range(1, count+1))
        paths.append(points)
    drawing['strokes'] = paths
    return key, drawing
